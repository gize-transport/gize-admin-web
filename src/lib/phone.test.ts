import { describe, expect, it } from "vitest";
import { mobileE164 } from "./phone";

describe("mobileE164", () => {
  it.each([
    ["0911234567", "+251911234567"],
    ["0711234567", "+251711234567"],
    ["911234567", "+251911234567"],
    ["+251911234567", "+251911234567"],
    ["251911234567", "+251911234567"],
    ["00251911234567", "+251911234567"],
    ["+251 (0) 911 23 45 67", "+251911234567"],
    ["0911-23-45-67", "+251911234567"],
    ["0911 23 45 67", "+251911234567"],
    ["  0911 234 567  ", "+251911234567"],
  ])("reads %j as %s", (typed, stored) => {
    expect(mobileE164(typed)).toBe(stored);
  });

  it.each([
    "",
    "0811234567",
    "091123456",
    "09112345678",
    "+1 911 234 567",
    "phone",
  ])("refuses %j", (typed) => {
    expect(mobileE164(typed)).toBeNull();
  });
});
